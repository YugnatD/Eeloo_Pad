#!/usr/bin/env python3
"""Generates main/navball_font.h: the glyphs used for the navball heading / pitch labels,
rendered once from a TrueType font into an anti-aliased atlas (fill alpha + dark outline alpha).

usage: gen_font.py [--font /usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf] [--size 38]
The atlas is sampled with bilinear filtering on the board, projected on the ball surface.
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFilter, ImageFont

CHARS = "0123456789NESW-"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--font', default='/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf')
    ap.add_argument('--size', type=int, default=38)
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'main', 'navball_font.h'))
    a = ap.parse_args()

    font = ImageFont.truetype(a.font, a.size)
    pad = 3                                            # room for the outline
    asc, desc = font.getmetrics()
    top = min(font.getbbox(c)[1] for c in CHARS)       # crop the empty space above the digits
    bot = max(font.getbbox(c)[3] for c in CHARS)
    h = bot - top + 2 * pad
    glyphs, x = [], 0
    for c in CHARS:
        w = int(font.getlength(c)) + 2 * pad
        glyphs.append((c, x, w))
        x += w
    W = x
    img = Image.new('L', (W, h), 0)
    d = ImageDraw.Draw(img)
    for c, gx, w in glyphs:
        d.text((gx + pad, pad - top), c, font=font, fill=255)
    edge = img.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(0.8))

    with open(a.out, 'w') as f:
        f.write('/* Generated by tools/gen_font.py from %s, size %d. Do not edit. */\n' % (os.path.basename(a.font), a.size))
        f.write('#pragma once\n#include <stdint.h>\n\n')
        f.write('#define NBF_H %d          /* glyph height (pixels) */\n#define NBF_W %d          /* atlas width */\n' % (h, W))
        f.write('#define NBF_N %d\n#define NBF_PAD %d        /* empty border of each glyph (outline room) */\n' % (len(glyphs), pad))
        f.write('static const struct { char c; uint16_t x; uint8_t w; } NBF_GLYPHS[NBF_N] = {\n')
        for c, gx, w in glyphs:
            f.write("    {'%s', %d, %d},\n" % (c, gx, w))
        f.write('};\n')
        for name, im in (('NBF_FILL', img), ('NBF_EDGE', edge)):
            px = list(im.tobytes())
            f.write('static const uint8_t %s[NBF_H * NBF_W] = {\n' % name)
            for i in range(0, len(px), 32):
                f.write('    ' + ','.join(str(v) for v in px[i:i + 32]) + ',\n')
            f.write('};\n')
    print('wrote %s: %d glyphs, atlas %dx%d' % (a.out, len(glyphs), W, h))


if __name__ == '__main__':
    main()
